const P = '/pepito/uploads';

export type ShopPetType = 'dog' | 'cat' | 'bird' | 'all';

export interface ShopCategory {
  slug: string;
  labelFa: string;
  labelEn?: string;
  petType: Exclude<ShopPetType, 'all'>;
  description: string;
  emoji: string;
}

export interface ShopBrand {
  id: string;
  labelFa: string;
  labelEn?: string;
}

export interface ShopProduct {
  id: string;
  slug: string;
  title: string;
  brandId: string;
  categorySlug: string;
  petTypes: Array<Exclude<ShopPetType, 'all'>>;
  /** قیمت فعلی تومان */
  priceToman: number;
  /** قیمت قبل از تخفیف (تومان) — اگر بیشتر از price باشد نشان‌دهنده تخفیف */
  compareAtToman?: number;
  image: string;
  /** گالری تصاویر (Digikala-style) — در صورت خالی بودن از image استفاده می‌شود */
  images?: string[];
  badge?: 'hot' | 'sale' | 'new' | 'limited';
  inStock: boolean;
  /** پارامترهای کارت محصول / جدول مشخصات (وزن، رنگ، سایز، …) */
  params: Record<string, string>;
  description: string;
  featured?: boolean;
  /** فروشنده نمایشی در باکس خرید (مثل دیجی‌کالا) */
  sellerName?: string;
  /** متن گارانتی / اصالت */
  warranty?: string;
  /** امتیاز ۰–۵ */
  rating?: number;
  reviewCount?: number;
  /** بولت‌های کوتاه زیر عنوان */
  highlights?: string[];
  /** عنوان انگلیسی (مثل دیجی‌کالا) */
  titleEn?: string;
  /** کد کالا / SKU */
  sku?: string;
  /** رنگ‌های قابل انتخاب */
  colors?: { labelFa: string; hex: string }[];
  /** سایز / وزن بسته‌بندی */
  sizes?: string[];
  /** توضیح ارسال */
  shippingNote?: string;
  /** شرایط مرجوعی */
  returnPolicy?: string;
  /** امتیاز رضایت از فروشنده ۰–۱۰۰ */
  sellerScore?: number;
  /** نقاط قوت (نظرات) */
  pros?: string[];
  /** نقاط ضعف (نظرات) */
  cons?: string[];
}

