export function seedMagazineEditorial(): number {
  ensureMagazineSchema();
  let count = 0;
  for (const article of EDITORIAL_ARTICLES) {
    upsertMagazineArticleBySlug(article);
    count += 1;
  }
  return count;
}

export function magazineEditorialSlugs(): string[] {
  return EDITORIAL_ARTICLES.map((a) => a.slug);
}
