function buildUserPrompt(ctx: AiConsultContext): string {
  const bits: string[] = [];
  if (ctx.patientName) bits.push(`نام کاربر: ${ctx.patientName}`);
  if (ctx.petName) bits.push(`نام پت: ${ctx.petName}`);
  const speciesFa = speciesLabelFa(ctx.petSpecies);
  if (speciesFa) bits.push(`گونه: ${speciesFa}`);
  if (ctx.petBreed) bits.push(`نژاد: ${ctx.petBreed}`);
  const intro =
    ctx.kind === 'support'
      ? 'کاربر از پشتیبانی پت‌دیت کمک می‌خواهد.'
      : ctx.kind === 'trainer'
        ? 'کاربر برای آموزش/رفتار پت راهنمایی می‌خواهد.'
        : 'دامپزشک آنلاین نیست. لطفاً راهنمایی عمومی بده.';
  const ask =
    ctx.userMessage?.trim() ||
    (ctx.kind === 'support'
      ? 'سلام؛ چطور می‌توانم کمکت کنم؟'
      : ctx.kind === 'trainer'
        ? 'پیام افتتاحیه بنویس: گرم سلام کن، حال صاحب و پت را بپرس، به عکس/پروفایل اشاره کن؛ هنوز برنامهٔ آموزشی کامل نریز. این دستورالعمل را بلند نگو و نگو «اول احوال‌پرسی بعد آموزش» — فقط انجام بده.'
        : 'برای مراقبت کلی از پت چه نکات مهمی داری؟');
  return [intro, bits.length ? bits.join(' · ') : null, '', ask].filter(Boolean).join('\n');
}

/** First trainer message: warm احوال‌پرسی + pet photo/profile — no curriculum dump. */
export function buildTrainerOpeningGreeting(
  ctx: Omit<AiConsultContext, 'kind' | 'userMessage' | 'history'>
): string {
  const owner = ctx.patientName?.trim() || 'دوست عزیز';
  const pet = ctx.petName?.trim() || 'پت';
  const hasPhoto = Boolean(ctx.petImageUrl?.trim());
  const speciesFa = speciesLabelFa(ctx.petSpecies);
  const profileBits = [
    speciesFa ? speciesFa : null,
    ctx.petBreed ? `نژاد ${ctx.petBreed}` : null,
    ctx.petAgeMonths != null && Number.isFinite(ctx.petAgeMonths)
      ? `حدود ${ctx.petAgeMonths} ماه`
      : null,
  ].filter(Boolean);

  const photoLine = hasPhoto
    ? `عکست از ${pet} رو هم دیدم، چه ملیح! یه نگاه به پروفایلش انداختم.`
    : `اگه یه عکس از ${pet} بفرستی (یا بذاری تو پروفایل) خوشحال می‌شم ببینمش — با دیدن قیافه‌ش بهتر راه می‌افتم.`;

  const profileLine = profileBits.length
    ? `از چیزی که تو پروفایل هست: ${profileBits.join('، ')}.`
    : `چند سالشه؟ نژادشم اگه می‌دونی بگو.`;

  const who = consultAgentName(ctx);
  const hellos = [
    `سلام ${owner} 👋 من ${who}ام. خوشحالم اینجایی.`,
    `${owner} جان سلام، ${who} هستم. قشنگ شد که اومدی سراغ آموزش.`,
    `سلام ${owner}! منم ${who}. از پت‌دیت آنلاین کنارت هستم.`,
  ];
  const hello = hellos[(owner.length + pet.length) % hellos.length]!;
  return [
    hello,
    ``,
    `راستش بگو خودت خوبی؟ ${pet} این روزا حالش چطوره — سرحال و بازیگوشه یا یه‌کم بی‌قراره؟`,
    photoLine,
    profileLine,
    ``,
    `هر وقت خواستی بگو روی چی کار کنیم؛ من اینجام.`,
  ].join('\n');
}

/** Simulated human typing pause before trainer AI replies (ms). */
export function trainerTypingDelayMs(replyText: string): number {
  const len = String(replyText || '').length;
  const scaled = 1500 + Math.floor(len * 12);
  return Math.max(1500, Math.min(4000, scaled));
}

