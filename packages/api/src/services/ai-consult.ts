function findTrainerTopic(message: string): TrainerTopic | null {
  const q = message.toLowerCase();
  const hits = TRAINER_TOPICS.filter((t) => t.match.test(q));
  if (!hits.length) return null;
  if (hits.length === 1) return hits[0]!;
  // When several topics match (e.g. قلاده + واکنش), prefer the more specific behavior topic.
  const priority: TrainerTopicId[] = [
    'dominance',
    'cat_litter',
    'cat_scratch',
    'cat_mojo',
    'bird',
    'exotic',
    'reactivity',
    'guarding',
    'sources',
    'separation',
    'fear',
    'bite',
    'bark',
    'potty',
    'crate',
    'recall',
    'stay',
    'sit',
    'jump',
    'leaveit',
    'clicker',
    'enrichment',
    'social',
    'puppy',
    'cat',
    'leash',
  ];
  hits.sort((a, b) => priority.indexOf(a.id) - priority.indexOf(b.id));
  return hits[0]!;
}

function findTrainerTopicFromHistory(
  ctx: AiConsultContext
): { topic: TrainerTopic; depth: number } | null {
  const msgs = [...(ctx.history ?? [])]
    .map((h) => h.content)
    .concat(ctx.userMessage ? [ctx.userMessage] : []);
  let topic: TrainerTopic | null = null;
  let depth = 0;
  for (const text of msgs) {
    const hit = findTrainerTopic(text);
    if (hit) {
      if (topic && topic.id === hit.id) depth += 1;
      else {
        topic = hit;
        depth = 1;
      }
    }
  }
  if (!topic) return null;
  return { topic, depth };
}

function isShortTrainerFollowUp(message: string): boolean {
  const normalized = message.replace(/\s+/g, ' ').trim();
  if (normalized.length > 64) return false;
  return /^(بله|آره|اره|باشه|مرسی|ممنون|بیشتر|ادامه|چطور|چجوری|چگونه|بعد|بعدش|؟|\?|ok|okay)([\s،.!؟]*)$|^(بیشتر\s+توضیح|ادامه\s+بده|مرحله\s+بعد|دقیق‌?تر|عمیق‌?تر|اگر\s+گیر)/i.test(
    normalized
  );
}

function formatTrainerTopicReply(
  ctx: AiConsultContext,
  topic: TrainerTopic,
  depth: number,
  opts?: { followUpLabel?: string }
): string {
  const body = depth >= 2 ? topic.deeper : topic.primary;
  const hasHistory = (ctx.history?.length ?? 0) > 0;
  // Never restate/echo the user's question or topic title — answer directly.
  const openings = hasHistory
    ? [
        `ببین من معمولاً این‌جوری جمعش می‌کنم:`,
        `خب بذار خودمونی بگم چی کار کنی:`,
        `راستش راهش اینه:`,
      ]
    : [
        `سلام، من ${AI_TRAINER_DISPLAY_NAME}ام. خوش اومدی — بریم سر اصل مطلب.`,
        `سلام! ${AI_TRAINER_DISPLAY_NAME} هستم. همین الان می‌گم چی کار کنیم.`,
      ];
  const seed = (ctx.userMessage?.length ?? 0) + (ctx.petName?.length ?? 0) + topic.id.length;
  const opening = opts?.followUpLabel
    ? opts.followUpLabel
    : openings[seed % openings.length]!;
  const spokenBody = humanizeTrainerOfflineProse(body);
  return [opening, '', spokenBody, '', ageAwareAside(ctx)].join('\n');
}

/** Offline topic body for tests / debugging. */
export function trainerTopicHint(message: string): string | null {
  const topic = findTrainerTopic(message);
  return topic ? topic.primary : null;
}

function trainerFollowUpReply(ctx: AiConsultContext): string | null {
  const q = ctx.userMessage?.trim() ?? '';
  const history = ctx.history ?? [];
  if (!history.length) return null;

  const lastUser = [...history].reverse().find((h) => h.role === 'user')?.content?.trim();
  if (isShortTrainerFollowUp(q) && lastUser) {
    const fromLast = findTrainerTopic(lastUser);
    const tracked = findTrainerTopicFromHistory({ ...ctx, userMessage: lastUser });
    const topic = fromLast || tracked?.topic;
    if (topic) {
      const depth = Math.max(2, (tracked?.depth ?? 1) + 1);
      return formatTrainerTopicReply(ctx, topic, depth, {
        followUpLabel: `باشه، بریم عمیق‌تر.`,
      });
    }
  }

  // Same-topic follow-up question (not just «بیشتر») → deeper protocol
  const current = findTrainerTopic(q);
  if (current) {
    const prior = history.some((h) => h.role === 'user' && findTrainerTopic(h.content)?.id === current.id);
    if (prior) {
      return formatTrainerTopicReply(ctx, current, 2, {
        followUpLabel: `ادامه بدیم — این بار می‌ریم سراغ گیرها و جزئیات:`,
      });
    }
  }
  return null;
}

